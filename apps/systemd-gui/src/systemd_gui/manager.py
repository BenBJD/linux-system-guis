"""Backend wrappers and data models for systemd services and timers."""

from dataclasses import dataclass, field
import os
import re
import subprocess
from linux_gui_core.runner.executor import ExecutionResult, SafeExecutor


@dataclass
class ServiceUnit:
    name: str
    load: str
    active: str
    sub: str
    description: str
    friendly_status: str = "Stopped"
    friendly_boot: str = "Manual only"


@dataclass
class TimerUnit:
    next_elapse: str
    left: str
    last_trigger: str
    passed: str
    unit: str
    activates: str
    schedule_summary: str = ""


@dataclass
class TimerConfig:
    """Configuration state of a systemd.timer(5) unit and its drop-in overrides."""

    unit_name: str = ""
    activates: str = ""
    description: str = ""
    fragment_path: str = ""
    dropin_paths: list[str] = field(default_factory=list)
    # Realtime (wallclock) trigger
    on_calendar: str = ""
    # Monotonic triggers (relative to starting points per systemd.timer(5) Table 1)
    on_boot_sec: str = ""
    on_startup_sec: str = ""
    on_active_sec: str = ""
    on_unit_active_sec: str = ""
    on_unit_inactive_sec: str = ""
    # Timing accuracy & jitter
    accuracy_sec: str = ""
    randomized_delay_sec: str = ""
    # Behavior flags
    persistent: bool = False
    wake_system: bool = False
    fixed_random_delay: bool = False
    on_clock_change: bool = False
    on_timezone_change: bool = False
    raw_unit_text: str = ""

    def summary_schedule(self) -> str:
        """Return a concise summary of configured timer triggers."""
        parts = []
        if self.on_calendar:
            parts.append(f"OnCalendar={self.on_calendar}")
        if self.on_boot_sec:
            parts.append(f"OnBootSec={self.on_boot_sec}")
        if self.on_startup_sec:
            parts.append(f"OnStartupSec={self.on_startup_sec}")
        if self.on_active_sec:
            parts.append(f"OnActiveSec={self.on_active_sec}")
        if self.on_unit_active_sec:
            parts.append(f"OnUnitActiveSec={self.on_unit_active_sec}")
        if self.on_unit_inactive_sec:
            parts.append(f"OnUnitInactiveSec={self.on_unit_inactive_sec}")
        if self.on_clock_change:
            parts.append("OnClockChange=true")
        if self.on_timezone_change:
            parts.append("OnTimezoneChange=true")
        if self.persistent:
            parts.append("Persistent=true")
        if self.randomized_delay_sec and self.randomized_delay_sec != "0":
            parts.append(f"RandomizedDelaySec={self.randomized_delay_sec}")
        if self.fixed_random_delay:
            parts.append("FixedRandomDelay=true")
        return ", ".join(parts) if parts else "(no triggers set)"

    def _timer_directives(self) -> list[str]:
        lines = []
        if self.activates and self.unit_name:
            default_svc = re.sub(r"\.timer$", ".service", self.unit_name)
            if self.activates != default_svc:
                lines.append(f"Unit={self.activates}")
        if self.on_calendar:
            lines.append(f"OnCalendar={self.on_calendar}")
        if self.on_boot_sec:
            lines.append(f"OnBootSec={self.on_boot_sec}")
        if self.on_startup_sec:
            lines.append(f"OnStartupSec={self.on_startup_sec}")
        if self.on_active_sec:
            lines.append(f"OnActiveSec={self.on_active_sec}")
        if self.on_unit_active_sec:
            lines.append(f"OnUnitActiveSec={self.on_unit_active_sec}")
        if self.on_unit_inactive_sec:
            lines.append(f"OnUnitInactiveSec={self.on_unit_inactive_sec}")
        if self.on_clock_change:
            lines.append("OnClockChange=true")
        if self.on_timezone_change:
            lines.append("OnTimezoneChange=true")
        if self.accuracy_sec:
            lines.append(f"AccuracySec={self.accuracy_sec}")
        if self.randomized_delay_sec:
            lines.append(f"RandomizedDelaySec={self.randomized_delay_sec}")
        if self.fixed_random_delay:
            lines.append("FixedRandomDelay=true")
        lines.append(f"Persistent={'true' if self.persistent else 'false'}")
        if self.wake_system:
            lines.append("WakeSystem=true")
        return lines

    def to_override_content(self) -> str:
        """Serialize as a systemd drop-in override file (override.conf).

        Per systemd.timer(5), assigning the empty string to OnCalendar= resets
        all prior timer trigger lists (both OnCalendar= and monotonic timers)
        defined in the vendor unit file before applying the new triggers.
        """
        lines = [
            "# Generated by systemd-gui — systemd.timer(5) drop-in override",
            "[Timer]",
            "# Empty assignment resets vendor timer triggers per systemd.timer(5)",
            "OnCalendar=",
        ]
        lines.extend(self._timer_directives())
        return "\n".join(lines) + "\n"

    def to_unit_file_content(self) -> str:
        """Serialize as a complete standalone .timer unit file."""
        desc = self.description or f"Timer for {self.activates or self.unit_name}"
        lines = [
            "[Unit]",
            f"Description={desc}",
            "",
            "[Timer]",
        ]
        lines.extend(self._timer_directives())
        lines.extend([
            "",
            "[Install]",
            "WantedBy=timers.target",
        ])
        return "\n".join(lines) + "\n"


class SystemdManager:
    # Matches full `systemctl list-timers --all --full --no-pager --no-legend --plain` rows:
    # NEXT (date or -/n/a) | LEFT | LAST (date or -/n/a) | PASSED | UNIT | ACTIVATES
    _TIMER_ROW_RE = re.compile(
        r"^(?P<next>-|n/a|[A-Za-z]{3}\s+\d{4}-\d{2}-\d{2}\s+\d{2}:\d{2}:\d{2}\s+\S+)\s+"
        r"(?P<left>-|n/a|.+?)\s+"
        r"(?P<last>-|n/a|[A-Za-z]{3}\s+\d{4}-\d{2}-\d{2}\s+\d{2}:\d{2}:\d{2}\s+\S+)\s+"
        r"(?P<passed>-|n/a|.+?)\s+"
        r"(?P<unit>\S+\.timer)\s+"
        r"(?P<activates>\S+)$"
    )

    @staticmethod
    def _translate_runtime_status(active: str, sub: str, load: str) -> str:
        """Translates systemd technical active/sub states into human-friendly status strings."""
        if load == "not-found":
            return "Not installed"
        if active == "failed" or sub == "failed":
            return "Crashed / Failed"
        if active == "active" and sub == "running":
            return "Running"
        if active == "active" and sub == "exited":
            return "Completed (one-shot)"
        if active == "active" and sub == "waiting":
            return "Idle / Waiting"
        if active == "inactive" or sub == "dead":
            return "Stopped"
        if active == "activating":
            return "Starting up..."
        if active == "deactivating":
            return "Stopping..."
        return f"⚪ {active} ({sub})"

    @staticmethod
    def _translate_boot_status(enablement: str) -> str:
        """Translates systemd unit file enablement into human-friendly boot startup strings."""
        clean = enablement.lower().strip()
        if "enabled" in clean:
            return "Runs on boot (Enabled)"
        if "disabled" in clean:
            return "Manual start only (Disabled)"
        if "masked" in clean:
            return "Blocked completely (Masked)"
        if "static" in clean:
            return "Dependency only (Starts if needed)"
        if "indirect" in clean:
            return "Managed by another unit"
        return "Unknown / Not found"

    @classmethod
    def get_unit_file_enablement(cls, user_mode: bool = False) -> dict[str, str]:
        """Maps unit file names to their boot enablement state (enabled, disabled, etc.)."""
        cmd = ["systemctl"]
        if user_mode:
            cmd.append("--user")
        cmd.extend(["list-unit-files", "--type=service", "--no-pager", "--no-legend", "--plain"])

        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        mapping = {}
        for line in res.stdout.splitlines():
            parts = line.split()
            if len(parts) >= 2:
                mapping[parts[0]] = parts[1]
        return mapping

    @classmethod
    def list_services(cls, user_mode: bool = False) -> list[ServiceUnit]:
        """Fetch list of service units with beginner-friendly state translations."""
        enablement_map = cls.get_unit_file_enablement(user_mode)

        cmd = ["systemctl"]
        if user_mode:
            cmd.append("--user")
        cmd.extend(["list-units", "--type=service", "--all", "--full", "--no-pager", "--no-legend", "--plain"])

        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        units = []
        for line in res.stdout.splitlines():
            clean_line = line.strip()
            while clean_line and clean_line[0] in ("●", "*", "•", "x"):
                clean_line = clean_line[1:].strip()

            parts = clean_line.split(maxsplit=4)
            if len(parts) >= 5:
                name = parts[0]
                load = parts[1]
                active = parts[2]
                sub = parts[3]
                desc = parts[4]

                if not name.endswith(".service"):
                    if len(parts) > 1 and parts[1].endswith(".service"):
                        name = parts[1]

                friendly_status = cls._translate_runtime_status(active, sub, load)
                raw_enable = enablement_map.get(name, "not-found" if load == "not-found" else "unknown")
                friendly_boot = cls._translate_boot_status(raw_enable)

                units.append(
                    ServiceUnit(
                        name=name,
                        load=load,
                        active=active,
                        sub=sub,
                        description=desc,
                        friendly_status=friendly_status,
                        friendly_boot=friendly_boot,
                    )
                )
        return units

    @classmethod
    def parse_list_timers_output(cls, stdout: str) -> list[TimerUnit]:
        """Parse output from `systemctl list-timers --all --full --no-pager --no-legend --plain`."""
        timers = []
        for line in stdout.splitlines():
            clean_line = line.strip()
            while clean_line and clean_line[0] in ("●", "*", "•"):
                clean_line = clean_line[1:].strip()
            if not clean_line:
                continue

            m = cls._TIMER_ROW_RE.match(clean_line)
            if m:
                timers.append(
                    TimerUnit(
                        next_elapse=m.group("next").strip(),
                        left=m.group("left").strip(),
                        last_trigger=m.group("last").strip(),
                        passed=m.group("passed").strip(),
                        unit=m.group("unit").strip(),
                        activates=m.group("activates").strip(),
                    )
                )
                continue

            parts = clean_line.split()
            if len(parts) >= 6:
                timers.append(
                    TimerUnit(
                        next_elapse=f"{parts[0]} {parts[1]}" if parts[0] != "-" else "-",
                        left=parts[2] if parts[0] != "-" else parts[1],
                        last_trigger=f"{parts[3]} {parts[4]}",
                        passed=parts[5],
                        unit=parts[-2] if len(parts) > 6 else parts[5],
                        activates=parts[-1],
                    )
                )
        return timers

    @classmethod
    def list_timers(cls, user_mode: bool = False) -> list[TimerUnit]:
        """Fetch list of active and inactive timers with their configured schedules."""
        cmd = ["systemctl"]
        if user_mode:
            cmd.append("--user")
        cmd.extend(["list-timers", "--all", "--full", "--no-pager", "--no-legend", "--plain"])

        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        timers = cls.parse_list_timers_output(res.stdout)
        for t in timers:
            cfg = cls.get_timer_config(t.unit, user_mode=user_mode, activates=t.activates)
            t.schedule_summary = cfg.summary_schedule()
        return timers

    @staticmethod
    def parse_timer_unit_text(unit_name: str, text: str, activates: str = "") -> TimerConfig:
        """Parse `systemctl cat <timer>` output (including drop-in files) into a TimerConfig."""
        default_activates = activates or re.sub(r"\.timer$", ".service", unit_name)
        cfg = TimerConfig(
            unit_name=unit_name,
            activates=default_activates,
            raw_unit_text=text,
        )
        section = ""
        trigger_Reset_keys = {
            "oncalendar",
            "onactivesec",
            "onbootsec",
            "onstartupsec",
            "onunitactivesec",
            "onunitinactivesec",
        }

        for raw_line in text.splitlines():
            line = raw_line.strip()
            if line.startswith("# /"):
                path_candidate = line[2:].strip()
                if path_candidate.endswith(".timer") and not cfg.fragment_path:
                    cfg.fragment_path = path_candidate
                elif path_candidate.endswith(".conf"):
                    cfg.dropin_paths.append(path_candidate)
                continue
            if not line or line.startswith("#") or line.startswith(";"):
                continue
            if line.startswith("[") and line.endswith("]"):
                section = line[1:-1].strip().lower()
                continue
            if "=" not in line:
                continue

            key, val = line.split("=", 1)
            key_low = key.strip().lower()
            val = val.strip()

            if section == "unit":
                if key_low == "description":
                    cfg.description = val
            elif section == "timer":
                # Per systemd.timer(5): assigning empty string to any timer trigger option
                # resets all prior monotonic and OnCalendar= timer lists.
                if key_low in trigger_Reset_keys and val == "":
                    cfg.on_calendar = ""
                    cfg.on_boot_sec = ""
                    cfg.on_startup_sec = ""
                    cfg.on_active_sec = ""
                    cfg.on_unit_active_sec = ""
                    cfg.on_unit_inactive_sec = ""
                    continue

                if key_low == "oncalendar":
                    cfg.on_calendar = val
                elif key_low == "onbootsec":
                    cfg.on_boot_sec = val
                elif key_low == "onstartupsec":
                    cfg.on_startup_sec = val
                elif key_low == "onactivesec":
                    cfg.on_active_sec = val
                elif key_low == "onunitactivesec":
                    cfg.on_unit_active_sec = val
                elif key_low == "onunitinactivesec":
                    cfg.on_unit_inactive_sec = val
                elif key_low == "accuracysec":
                    cfg.accuracy_sec = val
                elif key_low == "randomizeddelaysec":
                    cfg.randomized_delay_sec = val
                elif key_low == "persistent":
                    cfg.persistent = val.lower() in ("true", "yes", "1", "on")
                elif key_low == "wakesystem":
                    cfg.wake_system = val.lower() in ("true", "yes", "1", "on")
                elif key_low == "fixedrandomdelay":
                    cfg.fixed_random_delay = val.lower() in ("true", "yes", "1", "on")
                elif key_low == "onclockchange":
                    cfg.on_clock_change = val.lower() in ("true", "yes", "1", "on")
                elif key_low == "ontimezonechange":
                    cfg.on_timezone_change = val.lower() in ("true", "yes", "1", "on")
                elif key_low == "unit" and val:
                    cfg.activates = val

        return cfg

    @staticmethod
    def validate_calendar_expression(expr: str) -> tuple[bool, str]:
        """Run `systemd-analyze calendar <expr>` to validate an OnCalendar= expression."""
        clean = expr.strip()
        if not clean:
            return False, "Calendar expression is empty."
        try:
            res = subprocess.run(
                ["systemd-analyze", "calendar", clean],
                capture_output=True,
                text=True,
                check=False,
                timeout=3,
            )
            if res.returncode == 0:
                return True, res.stdout.strip()
            return False, (res.stderr or res.stdout or "Invalid calendar expression.").strip()
        except Exception as e:
            return False, str(e)

    @classmethod
    def _read_timer_unit_files_from_disk(cls, clean_name: str, user_mode: bool = False) -> str:
        """Fast-path: locate and concatenate a timer unit and its .d/*.conf drop-in files
        directly from standard systemd unit directories without spawning subprocesses.
        """
        if user_mode:
            search_dirs = [
                os.path.expanduser("~/.config/systemd/user"),
                "/etc/systemd/user",
                os.path.expanduser("~/.local/share/systemd/user"),
                "/usr/local/lib/systemd/user",
                "/usr/lib/systemd/user",
                "/lib/systemd/user",
            ]
        else:
            search_dirs = [
                "/etc/systemd/system",
                "/run/systemd/system",
                "/usr/local/lib/systemd/system",
                "/usr/lib/systemd/system",
                "/lib/systemd/system",
            ]

        fragment_path = ""
        for d in search_dirs:
            candidate = os.path.join(d, clean_name)
            if os.path.isfile(candidate):
                fragment_path = candidate
                break

        if not fragment_path:
            return ""

        chunks: list[str] = []
        try:
            with open(fragment_path, "r", encoding="utf-8", errors="replace") as f:
                chunks.append(f"# {fragment_path}\n{f.read()}")
        except OSError:
            return ""

        # Collect drop-ins in systemd precedence order (later dirs overridden by earlier dirs by filename)
        dropin_by_name: dict[str, str] = {}
        for d in reversed(search_dirs):
            dropin_dir = os.path.join(d, f"{clean_name}.d")
            if os.path.isdir(dropin_dir):
                try:
                    for entry in sorted(os.listdir(dropin_dir)):
                        if entry.endswith(".conf"):
                            full_dropin = os.path.join(dropin_dir, entry)
                            if os.path.isfile(full_dropin):
                                dropin_by_name[entry] = full_dropin
                except OSError:
                    pass

        for _, dropin_path in sorted(dropin_by_name.items()):
            try:
                with open(dropin_path, "r", encoding="utf-8", errors="replace") as f:
                    chunks.append(f"# {dropin_path}\n{f.read()}")
            except OSError:
                pass

        return "\n\n".join(chunks)

    @classmethod
    def get_timer_config(cls, unit_name: str, user_mode: bool = False, activates: str = "") -> TimerConfig:
        """Read a timer unit's configuration from disk (or via `systemctl cat` fallback)."""
        clean_name = unit_name.strip("● *• \t\n\r")
        if not clean_name:
            return TimerConfig()
        raw_text = cls._read_timer_unit_files_from_disk(clean_name, user_mode=user_mode)
        if not raw_text:
            cmd = ["systemctl"]
            if user_mode:
                cmd.append("--user")
            cmd.extend(["cat", clean_name, "--no-pager"])
            res = subprocess.run(cmd, capture_output=True, text=True, check=False)
            raw_text = res.stdout if res.returncode == 0 else ""
        return cls.parse_timer_unit_text(clean_name, raw_text, activates=activates)

    @staticmethod
    def get_timer_override_path(unit_name: str, user_mode: bool = False) -> str:
        clean = unit_name.strip("● *• \t\n\r") or "custom.timer"
        if not clean.endswith(".timer"):
            clean += ".timer"
        if user_mode:
            base = os.path.expanduser("~/.config/systemd/user")
        else:
            base = "/etc/systemd/system"
        return os.path.join(base, f"{clean}.d", "override.conf")

    @staticmethod
    def get_new_timer_unit_path(unit_name: str, user_mode: bool = False) -> str:
        clean = unit_name.strip("● *• \t\n\r") or "custom.timer"
        if not clean.endswith(".timer"):
            clean += ".timer"
        if user_mode:
            base = os.path.expanduser("~/.config/systemd/user")
        else:
            base = "/etc/systemd/system"
        return os.path.join(base, clean)

    @classmethod
    def save_timer_config(
        cls,
        config: TimerConfig,
        user_mode: bool = False,
        create_new_unit: bool = False,
    ) -> ExecutionResult:
        """Write a timer drop-in override (or new unit file) and run daemon-reload."""
        if create_new_unit:
            target_path = cls.get_new_timer_unit_path(config.unit_name, user_mode=user_mode)
            content = config.to_unit_file_content()
        else:
            target_path = cls.get_timer_override_path(config.unit_name, user_mode=user_mode)
            content = config.to_override_content()

        if user_mode:
            try:
                os.makedirs(os.path.dirname(target_path), exist_ok=True)
                with open(target_path, "w", encoding="utf-8") as f:
                    f.write(content)
                reload_res = SafeExecutor.run_command(["systemctl", "--user", "daemon-reload"], elevated=False)
                return ExecutionResult(
                    success=reload_res.success,
                    stdout=reload_res.stdout,
                    stderr=reload_res.stderr,
                    command_executed=f"write {target_path} && systemctl --user daemon-reload",
                )
            except Exception as e:
                return ExecutionResult(
                    success=False,
                    stdout="",
                    stderr=str(e),
                    command_executed=f"write {target_path}",
                )
        else:
            import tempfile
            with tempfile.NamedTemporaryFile("w", delete=False, encoding="utf-8") as tf:
                tf.write(content)
                temp_path = tf.name
            try:
                parent_dir = os.path.dirname(target_path)
                script = (
                    f"mkdir -p '{parent_dir}' && "
                    f"cp '{temp_path}' '{target_path}' && "
                    f"chmod 644 '{target_path}' && "
                    f"systemctl daemon-reload"
                )
                return SafeExecutor.run_command(["bash", "-c", script], elevated=True)
            finally:
                if os.path.exists(temp_path):
                    os.remove(temp_path)

    @classmethod
    def revert_timer_override(cls, unit_name: str, user_mode: bool = False) -> ExecutionResult:
        """Remove a timer's override.conf drop-in and reload the systemd daemon."""
        override_path = cls.get_timer_override_path(unit_name, user_mode=user_mode)
        if user_mode:
            try:
                if os.path.exists(override_path):
                    os.remove(override_path)
                return SafeExecutor.run_command(["systemctl", "--user", "daemon-reload"], elevated=False)
            except Exception as e:
                return ExecutionResult(False, "", str(e), f"rm -f {override_path}")
        else:
            script = f"rm -f '{override_path}' && systemctl daemon-reload"
            return SafeExecutor.run_command(["bash", "-c", script], elevated=True)

    @staticmethod
    def get_unit_status(unit_name: str, user_mode: bool = False) -> str:
        clean_name = unit_name.strip("● *• \t\n\r")
        if not clean_name:
            return ""

        cmd = ["systemctl"]
        if user_mode:
            cmd.append("--user")
        cmd.extend(["status", clean_name, "--no-pager"])
        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        return res.stdout or res.stderr

    @staticmethod
    def build_command_str(action: str, unit: str, user_mode: bool = False) -> str:
        clean_unit = unit.strip("● *• \t\n\r")
        prefix = "systemctl --user" if user_mode else "sudo systemctl"
        return f"{prefix} {action} {clean_unit}".strip()

    @staticmethod
    def execute_unit_action(action: str, unit: str, user_mode: bool = False) -> ExecutionResult:
        clean_unit = unit.strip("● *• \t\n\r")
        cmd = ["systemctl"]
        if user_mode:
            cmd.append("--user")
        cmd.extend(action.split() + ([clean_unit] if clean_unit else []))
        elevated = not user_mode
        return SafeExecutor.run_command(cmd, elevated=elevated)
